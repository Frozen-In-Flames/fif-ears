"""Contract tests for the fif-smf-1 sidecar role of fif-ears.

A fif-smf-1 bundle (see the Frozen In Flames SMF contract) names a
fif-ears report as its `ears_report` member and relies on specific
fields: summary.tempo_bpm and summary.key for the headline, the
per-layer results under `layers`, and honest nulls where a layer
cannot run. These tests produce a report from the bundled fixture
tests/fixtures/contract_mix.wav (ground truth: 120 BPM clicks over a
C major triad, generated by tests/fixtures/generate_fixture.py; this
repo bundles no third-party audio) through the same analyze_file path
the CLI uses, read report.json back from disk, and validate the
fields the sidecar consumes against SCHEMA.md. A silence control
asserts the null shape a consumer must handle.

Run: python -m unittest discover -s tests -v   (from the repo root)
"""

import json
import os
import sys
import tempfile
import unittest

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from ears.report import analyze_file, build_report  # noqa: E402

FIXTURE = os.path.join(os.path.dirname(__file__), "fixtures",
                       "contract_mix.wav")
LAYERS = ["signal", "rhythm", "structure", "harmony", "words",
          "events", "expression"]


class TestContractReport(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="fif-ears-contract-")
        cls.returned = analyze_file(FIXTURE, cls.tmp)
        with open(os.path.join(cls.tmp, "report.json")) as fh:
            cls.report = json.load(fh)  # the file on disk is the contract

    def test_disk_report_matches_returned_report(self):
        self.assertEqual(self.report["summary"], self.returned["summary"])
        self.assertEqual(self.report["tool"], self.returned["tool"])

    def test_top_level_shape(self):
        r = self.report
        self.assertEqual(r["tool"]["name"], "fif-ears")
        self.assertIsInstance(r["tool"]["version"], str)
        self.assertEqual(r["input"]["file"], "contract_mix.wav")
        for key in ("duration_s", "tempo_bpm", "key", "sections",
                    "words_status"):
            self.assertIn(key, r["summary"])
        self.assertEqual(sorted(r["layers"].keys()), sorted(LAYERS))
        for name in LAYERS:
            self.assertIsInstance(r["layers"][name]["status"], str,
                                  f"layer {name} carries no status")

    def test_sidecar_fields_against_ground_truth(self):
        s = self.report["summary"]
        self.assertAlmostEqual(s["duration_s"], 8.0, delta=0.05)
        # Ground truth 120 BPM clicks.
        self.assertIsNotNone(s["tempo_bpm"])
        self.assertAlmostEqual(s["tempo_bpm"], 120.0, delta=2.5)
        # Ground truth C major triad.
        self.assertEqual(s["key"], "C major")
        self.assertIsInstance(s["sections"], int)
        self.assertGreaterEqual(s["sections"], 1)

    def test_layer_fields_the_sidecar_relies_on(self):
        layers = self.report["layers"]
        rhy = layers["rhythm"]
        self.assertEqual(rhy["status"], "ok")
        self.assertAlmostEqual(rhy["tempo_bpm"],
                               self.report["summary"]["tempo_bpm"],
                               delta=1e-9)
        self.assertTrue(rhy["onsets"])
        self.assertTrue(rhy["beat_times"])
        self.assertGreater(rhy["tempo_confidence"], 0.5)
        har = layers["harmony"]
        self.assertEqual(har["status"], "ok")
        self.assertEqual(har["key"], "C major")
        self.assertEqual(har["key_root"], "C")
        self.assertEqual(har["key_mode"], "major")
        self.assertEqual(len(har["mean_chroma"]), 12)
        self.assertIsNotNone(har["dominant_pitch"])
        sig = layers["signal"]
        self.assertEqual(sig["sample_rate"], 22050)
        self.assertEqual(sig["channels"], 1)

    def test_words_layer_nulls_when_it_cannot_run(self):
        wrd = self.report["layers"]["words"]
        self.assertIn(wrd["status"], ("ok", "not_installed", "error"))
        self.assertEqual(self.report["summary"]["words_status"],
                         wrd["status"])
        if wrd["status"] != "ok":
            self.assertIsNone(wrd["transcript"])
            self.assertIsNone(wrd["engine"])
            self.assertIn("openai-whisper", wrd["optional_dependencies"])
            self.assertIn("faster-whisper", wrd["optional_dependencies"])

    def test_silence_report_is_all_nulls_where_layers_cannot_run(self):
        path = os.path.join(self.tmp, "silence.wav")
        wavfile.write(path, 22050,
                      np.zeros(4 * 22050, dtype=np.int16))
        r = build_report(path)
        self.assertIsNone(r["summary"]["tempo_bpm"])
        self.assertIsNone(r["summary"]["key"])
        self.assertIsNone(r["layers"]["rhythm"]["tempo_bpm"])
        self.assertIsNone(r["layers"]["rhythm"]["beat_period_s"])
        self.assertIsNone(r["layers"]["harmony"]["dominant_pitch"])
        self.assertIsNone(r["layers"]["harmony"]["key"])
        groove = r["layers"]["expression"]["groove"]
        self.assertIsNone(groove["beat_deviation_mean_ms"])
        self.assertIsNone(groove["offbeat_delay_ms"])
        # The nulls survive JSON serialization, which is what a
        # sidecar consumer actually reads.
        parsed = json.loads(json.dumps(r))
        self.assertIsNone(parsed["summary"]["tempo_bpm"])
        self.assertIsNone(parsed["layers"]["harmony"]["key"])


if __name__ == "__main__":
    unittest.main()
